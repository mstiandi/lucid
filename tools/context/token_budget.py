"""
token预算，每个节点对应的最大token量，以及token估计函数，共后续prompt_builder调用。

  ┌───────────────┬─────────────┬──────────────────────────────┬─────────────────────┐
  │     节点      │ 静态 prompt │           动态数据           │    会累积增长？     │
  ├───────────────┼─────────────┼──────────────────────────────┼─────────────────────┤
  │ preprocess    │     5KB     │ 用户最新消息                 │   ❌ 每轮只新消息   │
  ├───────────────┼─────────────┼──────────────────────────────┼─────────────────────┤
  │ signals       │    12KB     │ 用户最新消息                 │   ❌ 每轮只新消息   │
  ├───────────────┼─────────────┼──────────────────────────────┼─────────────────────┤
  │ evidence      │     6KB     │ all_signals + pending claims │ ✅ behaviors 一直涨 │
  ├───────────────┼─────────────┼──────────────────────────────┼─────────────────────┤
  │ alternative   │     7KB     │ all_signals + pending claims │         ✅          │
  ├───────────────┼─────────────┼──────────────────────────────┼─────────────────────┤
  │ info_symmetry │     6KB     │ all_signals + pending claims │         ✅          │
  ├───────────────┼─────────────┼──────────────────────────────┼─────────────────────┤
  │ summary       │     1KB     │ pending claims               │   ❌ 每轮都是新的   │
  └───────────────┴─────────────┴──────────────────────────────┴─────────────────────┘


    总结：preprocess/signals/summary 不需要预算 ≠ 它们 token
  少。而是它们吃的是单轮数据，没有累积泄露风险，如果用户输入超长到爆 64K，那是用户的锅，不是系统的锅。
  evidence/alternative/info_symmetry 的 token 增长是系统的锅——all_signals_reducer 只加不减。  

"""

# 最大token限制量，注意DEEPSEEK的上下文窗口限制是64K
MAX_TOKEN_MAP = {
    "evidence_node": 12000,  # 12K
    "alternative_explanation_node": 12000,  # 12K
    "information_symmetry_node": 10000,  # 10K
}


# 估计token数量的函数
def estimate_token_count(text: str) -> int:
    """估计文本的token数量。粗略估计：每2个字符约1个token。"""
    return max(1, int(len(text) / 2))


